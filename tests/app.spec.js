test('key titles persist, survive reimport, and can be edited or removed', async ({ page }) => {
  const key = await generateIdentity({ name: 'Original identity', email: '', passphrase: 'title test passphrase' });
  await page.goto('/');
  await page.getByRole('button', { name: /Keyring/ }).click();
  await page.locator('#import-title').fill('Work key');
  await page.locator('#key-text').fill(key.privateKey);
  await page.getByRole('button', { name: 'Import into keyring' }).click();
  await expect(page.locator('.key-card h2')).toHaveText('Work key');
  await expect(page.locator('.key-card')).toContainText('Original identity');
  await page.reload();
  await page.getByRole('button', { name: /Keyring/ }).click();
  await expect(page.locator('.key-card h2')).toHaveText('Work key');
  await page.locator('#key-text').fill(key.publicKey);
  await page.getByRole('button', { name: 'Import into keyring' }).click();
  await expect(page.locator('#key-text')).toHaveValue('');
  await expect(page.locator('.key-card h2')).toHaveText('Work key');
  await expect(page.getByRole('button', { name: 'Backup private' })).toBeVisible();
  await page.locator('.key-title-form input').fill('Personal key');
  await page.getByRole('button', { name: 'Save title' }).click();
  await expect(page.locator('.key-card h2')).toHaveText('Personal key');
  await page.getByRole('button', { name: 'Messages & files' }).click();
  await expect(page.locator('#recipients')).toContainText('Personal key');
  await expect(page.locator('#recipients')).toContainText('Original identity');
  await page.getByRole('tab', { name: 'Decrypt', exact: true }).click();
  await expect(page.locator('#identity option').last()).toHaveText('Personal key — Original identity');
  await page.getByRole('button', { name: /Keyring/ }).click();
  await page.locator('.key-title-form input').fill('');
  await page.getByRole('button', { name: 'Save title' }).click();
  await expect(page.locator('.key-card h2')).toHaveText('Original identity');
});

test('key import, encryption/decryption, session clearing, and offline reload', async ({ page, context }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const passphrase = 'browser testing passphrase';
  const key = await generateIdentity({ name: 'Browser Test', email: '', passphrase });
  await page.goto('/');
  await expect(page.locator('#offline-state')).toHaveText('Ready for offline use');
  await page.getByRole('button', { name: /Keyring/ }).click();
  await page.locator('#key-text').fill(key.privateKey);
  await page.getByRole('button', { name: 'Import into keyring' }).click();
  await expect(page.locator('#key-count')).toHaveText('1');
  await page.getByRole('button', { name: 'Messages & files' }).click();
  await page.locator('#message').fill('A private browser message.');
  await page.locator('#recipients input').check();
  await page.locator('#run').click();
  await expect(page.locator('#result')).toHaveValue(/BEGIN PGP MESSAGE/);
  const encrypted = await page.locator('#result').inputValue();
  await page.getByRole('tab', { name: 'Decrypt', exact: true }).click();
  await page.locator('#message').fill(encrypted);
  await page.locator('#identity').selectOption({ label: 'Browser Test' });
  await page.locator('#passphrase').fill(passphrase);
  await page.locator('#run').click();
  await expect(page.locator('#result')).toHaveValue('A private browser message.');
  await expect(page.locator('#passphrase')).toHaveValue('');
  await page.locator('#clear').click();
  await expect(page.locator('#result')).toHaveValue('');
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator('h1').first()).toHaveText('Messages & files');
  await expect(page.locator('#key-count')).toHaveText('1');
  await page.locator('#message').fill('Offline message');
  await page.locator('#recipients input').check();
  await page.locator('#run').click();
  await expect(page.locator('#result')).toHaveValue(/BEGIN PGP MESSAGE/);
  expect(errors).toEqual([]);
});

