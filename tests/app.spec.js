test('install button uses browser prompt and handles dismissal and installation', async ({ page }) => {
  await page.goto('/');
  const button = page.locator('header [data-install]');
  await expect(button).toHaveText('Install as PWA');
  await page.evaluate(() => {
    const event = new Event('beforeinstallprompt', { cancelable: true });
    event.prompt = async () => { window.installPromptCalled = true; };
    event.userChoice = Promise.resolve({ outcome: 'dismissed' });
    window.dispatchEvent(event);
  });
  await button.click();
  await expect(page.locator('#notice')).toContainText('Installation dismissed');
  expect(await page.evaluate(() => window.installPromptCalled)).toBe(true);
  await expect(button).toBeVisible();
  await page.evaluate(() => window.dispatchEvent(new Event('appinstalled')));
  await expect(button).toBeHidden();
  await expect(page.locator('#notice')).toContainText('PGPWA installed');
});

