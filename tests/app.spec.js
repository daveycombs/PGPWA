test('larger files require opt-in and round trip offline through the worker', async ({ page, context }, testInfo) => {
  test.setTimeout(90000);
  const passphrase = 'large file test passphrase';
  const key = await generateIdentity({ name: 'File test', email: '', passphrase });
  await page.goto('/');
  await expect(page.locator('#offline-state')).toHaveText('Ready for offline use');
  await page.getByRole('button', { name: /Keyring/ }).click();
  await page.locator('#key-text').fill(key.privateKey);
  await page.getByRole('button', { name: 'Import into keyring' }).click();
  await expect(page.locator('#key-count')).toHaveText('1');
  await page.getByRole('button', { name: 'Messages & files' }).click();
  await page.locator('input[value=file]').check();
  const original = Buffer.alloc(21 * 1024 * 1024, 173);
  original[0] = 0; original[original.length - 1] = 255;
  await page.locator('#file').setInputFiles({ name: 'large.bin', mimeType: 'application/octet-stream', buffer: original });
  await page.locator('#recipients input').check();
  await page.locator('#run').click();
  await expect(page.locator('#notice')).toContainText('20 MB limit');
  await page.locator('#large-files').check();
  await context.setOffline(true);
  await page.locator('#run').click();
  await expect(page.locator('#download')).toBeVisible({ timeout: 30000 });
  const encryptedDownload = page.waitForEvent('download');
  await page.locator('#download').click();
  const encrypted = await encryptedDownload;
  expect(encrypted.suggestedFilename()).toBe('large.bin.pgp');
  const encryptedPath = testInfo.outputPath('large.bin.pgp');
  await encrypted.saveAs(encryptedPath);
  await page.getByRole('tab', { name: 'Decrypt', exact: true }).click();
  await page.locator('#file').setInputFiles(encryptedPath);
  await page.locator('#identity').selectOption({ label: 'File test' });
  await page.locator('#passphrase').fill(passphrase);
  await page.locator('#run').click();
  await expect(page.locator('#download')).toBeVisible({ timeout: 30000 });
  const decryptedDownload = page.waitForEvent('download');
  await page.locator('#download').click();
  const decryptedPath = testInfo.outputPath('decrypted.bin');
  await (await decryptedDownload).saveAs(decryptedPath);
  expect((await readFile(decryptedPath)).equals(original)).toBe(true);
  await page.getByRole('tab', { name: 'Encrypt', exact: true }).click();
  await page.locator('#run').click();
  await page.locator('#clear').click();
  await expect(page.locator('#run')).toBeEnabled();
  await expect(page.locator('#result-content')).toBeHidden();
});
